/*******************************************************************************
  Function:
    void SYS_Initialize ( void *data )

  Summary:
    Initializes the board, services, drivers, application and other modules.

  Remarks:
 */

void SYS_Initialize ( void* data )
{

    /* MISRAC 2012 deviation block start */
    /* MISRA C-2012 Rule 2.2 deviated in this file.  Deviation record ID -  H3_MISRAC_2012_R_2_2_DR_1 */

    EFC_Initialize();
  
    CLOCK_Initialize();
	PIO_Initialize();
    
    XDMAC_Initialize();
    UART0_Initialize();
	UART2_Initialize();

	SYSTICK_TimerInitialize();
	RSWDT_REGS->RSWDT_MR = RSWDT_MR_WDDIS_Msk;	// Disable RSWDT 

	WDT_REGS->WDT_MR = WDT_MR_WDDIS_Msk; 		// Disable WDT 

    MCAN1_Initialize();
    
    TC0_CH0_CompareInitialize();    // 
    TC0_CH1_CompareInitialize();    // PWM mode for ADC CONV pin
    TC0_CH2_CompareInitialize();
    TC1_CH0_CompareInitialize();
    TC2_CH0_CompareInitialize();
    TC2_CH1_CompareInitialize();

    TC3_CH0_TimerInitialize();
    TC3_CH1_TimerInitialize();
    
    USART0_SPI_Initialize();

    USART2_SPI_Initialize();

    TWIHS0_Initialize();
    TWIHS1_Initialize();
    TWIHS2_Initialize();
    
    spi_io_init(&spi0);
    SPI0_Initialize();
    
    spi_io_init(&spi1);
    SPI1_Initialize();
    
    AFEC0_Initialize();
    AFEC1_Initialize();

    NVIC_Initialize();
    /* MISRAC 2012 deviation block end */
}

